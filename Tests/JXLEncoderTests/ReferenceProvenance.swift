import Foundation

/// Locates the checked-out repository from this file's own path. The pin record
/// and the provenance manifest live under `Reference/`, outside any test bundle,
/// so the provenance tests read them from the source tree.
enum RepositoryLayout {
	static var root: URL {
		URL(fileURLWithPath: #filePath)
			.deletingLastPathComponent()  // JXLEncoderTests
			.deletingLastPathComponent()  // Tests
			.deletingLastPathComponent()
	}

	static var pinRecord: URL { root.appendingPathComponent("Reference/libjxl.pin") }
	static var provenanceManifest: URL {
		root.appendingPathComponent("Reference/provenance.tsv")
	}
}

/// `Reference/libjxl.pin`: the single record of which libjxl the reference
/// tools build against. Shell-sourceable `KEY=value` lines so the reference
/// scripts and these tests read the same file; `#` starts a comment.
struct PinRecord {
	let values: [String: String]

	init(contentsOf url: URL) throws {
		let text = try String(contentsOf: url, encoding: .utf8)
		var dict: [String: String] = [:]
		for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
			let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
			if trimmed.isEmpty || trimmed.hasPrefix("#") {
				continue
			}
			guard let eqIndex = trimmed.firstIndex(of: "=") else {
				continue
			}
			let key = String(trimmed[..<eqIndex]).trimmingCharacters(
				in: .whitespacesAndNewlines)
			var val = String(trimmed[trimmed.index(after: eqIndex)...])
				.trimmingCharacters(in: .whitespacesAndNewlines)
			if (val.hasPrefix("\"") && val.hasSuffix("\"") && val.count >= 2)
				|| (val.hasPrefix("'") && val.hasSuffix("'") && val.count >= 2)
			{
				val = String(val.dropFirst().dropLast())
			}
			dict[key] = val
		}
		self.values = dict
	}

	subscript(key: String) -> String? { values[key] }
}

/// Where a committed reference artifact came from. Anything not reproducible
/// from the pinned full libjxl says so here rather than in prose.
enum ProvenanceOrigin: String, CaseIterable {
	/// Produced by the pinned full libjxl recorded in `libjxl.pin`.
	case fullLibjxl = "full-libjxl"
	/// Produced by libjxl-tiny, which is not pinned; frozen until retargeted.
	case inheritedTiny = "inherited-tiny"
	/// Produced by libjpeg-turbo's tools at the version the row records.
	case libjpegTurbo = "libjpeg-turbo"
	/// Captured from a CPU instruction on the host; only regenerable on that
	/// architecture.
	case hostArm64 = "host-arm64"
	/// Supplied by hand, not generated by any tool in this repository.
	case handSupplied = "hand-supplied"
}

enum ProvenanceKind: String {
	/// A file under a test target's `Fixtures/`, checked by content hash.
	case fixture
	/// A generated table compiled into `Sources/`, checked by its header.
	case table
	/// Expected values written inline in a test file rather than a fixture.
	case inline
}

/// One row of `Reference/provenance.tsv`. Columns, tab-separated, in order:
/// path, kind, sha256, origin, generator, invocation, input, upstream, config,
/// consumers.
///
/// `sha256` is present exactly for `fixture` rows and `-` otherwise.
/// `invocation` is the command that produced the artifact and `input` what it
/// read; either is `unrecorded` when the repository doesn't know, so a
/// regenerator can see the gap instead of guessing. `consumers` is a
/// comma-separated list of test files, or `-`.
struct ProvenanceRow: Equatable {
	let path: String
	let kind: ProvenanceKind
	let sha256: String?
	let origin: ProvenanceOrigin
	let generator: String
	let invocation: String
	let input: String
	let upstream: String
	let config: String
	let consumers: [String]
}

enum ProvenanceError: Error, Equatable {
	case invalidColumnCount(line: String, count: Int)
	case malformedRow(String)
	case invalidKind(String)
	case invalidOrigin(String)
	case invalidDigest(String)
}

struct ProvenanceManifest {
	let rows: [ProvenanceRow]

	/// Throws on a malformed row (wrong column count, unknown kind or origin,
	/// a digest on the wrong kind of row) rather than skipping it, so a typo
	/// can't hide a fixture. Lines starting with `#` are comments.
	init(text: String) throws {
		var parsedRows: [ProvenanceRow] = []
		for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
			let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
			if trimmed.isEmpty || trimmed.hasPrefix("#") {
				continue
			}
			let columns = line.split(separator: "\t", omittingEmptySubsequences: false)
				.map(String.init)
			guard columns.count == 10 else {
				throw ProvenanceError.invalidColumnCount(
					line: String(line), count: columns.count)
			}
			let path = columns[0].trimmingCharacters(in: .whitespacesAndNewlines)
			guard !path.isEmpty else {
				throw ProvenanceError.malformedRow("Empty path")
			}
			guard
				let kind = ProvenanceKind(
					rawValue: columns[1].trimmingCharacters(
						in: .whitespacesAndNewlines))
			else {
				throw ProvenanceError.invalidKind(columns[1])
			}
			let shaRaw = columns[2].trimmingCharacters(in: .whitespacesAndNewlines)
			let sha: String?
			if kind == .fixture {
				guard
					shaRaw.count == 64
						&& shaRaw.allSatisfy({
							$0.isHexDigit && !$0.isUppercase
						})
				else {
					throw ProvenanceError.invalidDigest(
						"Fixture must have 64-char lowercase hex sha256: \(shaRaw)"
					)
				}
				sha = shaRaw
			} else {
				guard shaRaw == "-" else {
					throw ProvenanceError.invalidDigest(
						"Non-fixture must have '-' for sha256: \(shaRaw)")
				}
				sha = nil
			}
			guard
				let origin = ProvenanceOrigin(
					rawValue: columns[3].trimmingCharacters(
						in: .whitespacesAndNewlines))
			else {
				throw ProvenanceError.invalidOrigin(columns[3])
			}
			let generator = columns[4].trimmingCharacters(in: .whitespacesAndNewlines)
			guard !generator.isEmpty else {
				throw ProvenanceError.malformedRow("Empty generator")
			}
			let invocation = columns[5].trimmingCharacters(in: .whitespacesAndNewlines)
			guard !invocation.isEmpty else {
				throw ProvenanceError.malformedRow("Empty invocation")
			}
			let input = columns[6].trimmingCharacters(in: .whitespacesAndNewlines)
			guard !input.isEmpty else {
				throw ProvenanceError.malformedRow("Empty input")
			}
			let upstream = columns[7].trimmingCharacters(in: .whitespacesAndNewlines)
			guard !upstream.isEmpty else {
				throw ProvenanceError.malformedRow("Empty upstream")
			}
			let config = columns[8].trimmingCharacters(in: .whitespacesAndNewlines)
			guard !config.isEmpty else {
				throw ProvenanceError.malformedRow("Empty config")
			}
			let consumersRaw = columns[9].trimmingCharacters(
				in: .whitespacesAndNewlines)
			guard !consumersRaw.isEmpty else {
				throw ProvenanceError.malformedRow("Empty consumers")
			}
			let consumers: [String]
			if consumersRaw == "-" {
				consumers = []
			} else {
				consumers = consumersRaw.split(separator: ",").map {
					$0.trimmingCharacters(in: .whitespacesAndNewlines)
				}
			}

			parsedRows.append(
				ProvenanceRow(
					path: path,
					kind: kind,
					sha256: sha,
					origin: origin,
					generator: generator,
					invocation: invocation,
					input: input,
					upstream: upstream,
					config: config,
					consumers: consumers
				)
			)
		}
		self.rows = parsedRows
	}

	init(contentsOf url: URL) throws {
		try self.init(text: String(decoding: try Data(contentsOf: url), as: UTF8.self))
	}
}

/// SHA-256 over raw bytes, lowercase hex. Foundation on Linux has no digest
/// API and the core tests must run there.
func sha256Hex(_ bytes: [UInt8]) -> String {
	let k: [UInt32] = [
		0x428a_2f98, 0x7137_4491, 0xb5c0_fbcf, 0xe9b5_dba5,
		0x3956_c25b, 0x59f1_11f1, 0x923f_82a4, 0xab1c_5ed5,
		0xd807_aa98, 0x1283_5b01, 0x2431_85be, 0x550c_7dc3,
		0x72be_5d74, 0x80de_b1fe, 0x9bdc_06a7, 0xc19b_f174,
		0xe49b_69c1, 0xefbe_4786, 0x0fc1_9dc6, 0x240c_a1cc,
		0x2de9_2c6f, 0x4a74_84aa, 0x5cb0_a9dc, 0x76f9_88da,
		0x983e_5152, 0xa831_c66d, 0xb003_27c8, 0xbf59_7fc7,
		0xc6e0_0bf3, 0xd5a7_9147, 0x06ca_6351, 0x1429_2967,
		0x27b7_0a85, 0x2e1b_2138, 0x4d2c_6dfc, 0x5338_0d13,
		0x650a_7354, 0x766a_0abb, 0x81c2_c92e, 0x9272_2c85,
		0xa2bf_e8a1, 0xa81a_664b, 0xc24b_8b70, 0xc76c_51a3,
		0xd192_e819, 0xd699_0624, 0xf40e_3585, 0x106a_a070,
		0x19a4_c116, 0x1e37_6c08, 0x2748_774c, 0x34b0_bcb5,
		0x391c_0cb3, 0x4ed8_aa4a, 0x5b9c_ca4f, 0x682e_6ff3,
		0x748f_82ee, 0x78a5_636f, 0x84c8_7814, 0x8cc7_0208,
		0x90be_fffa, 0xa450_6ceb, 0xbef9_a3f7, 0xc671_78f2,
	]

	var h: [UInt32] = [
		0x6a09_e667, 0xbb67_ae85, 0x3c6e_f372, 0xa54f_f53a,
		0x510e_527f, 0x9b05_688c, 0x1f83_d9ab, 0x5be0_cd19,
	]

	var msg = bytes
	let bitLength = UInt64(bytes.count) &* 8
	msg.append(0x80)
	while (msg.count % 64) != 56 {
		msg.append(0)
	}
	for shift in stride(from: 56, through: 0, by: -8) {
		msg.append(UInt8((bitLength >> shift) & 0xff))
	}

	var w = [UInt32](repeating: 0, count: 64)
	for chunkStart in stride(from: 0, to: msg.count, by: 64) {
		for i in 0..<16 {
			let j = chunkStart + i * 4
			w[i] =
				(UInt32(msg[j]) << 24)
				| (UInt32(msg[j + 1]) << 16)
				| (UInt32(msg[j + 2]) << 8)
				| UInt32(msg[j + 3])
		}
		for i in 16..<64 {
			let s0 =
				(w[i - 15] >> 7 | w[i - 15] << 25)
				^ (w[i - 15] >> 18 | w[i - 15] << 14)
				^ (w[i - 15] >> 3)
			let s1 =
				(w[i - 2] >> 17 | w[i - 2] << 15)
				^ (w[i - 2] >> 19 | w[i - 2] << 13)
				^ (w[i - 2] >> 10)
			w[i] = w[i - 16] &+ s0 &+ w[i - 7] &+ s1
		}

		var a = h[0]
		var b = h[1]
		var c = h[2]
		var d = h[3]
		var e = h[4]
		var f = h[5]
		var g = h[6]
		var hVal = h[7]

		for i in 0..<64 {
			let s1 = (e >> 6 | e << 26) ^ (e >> 11 | e << 21) ^ (e >> 25 | e << 7)
			let ch = (e & f) ^ (~e & g)
			let temp1 = hVal &+ s1 &+ ch &+ k[i] &+ w[i]
			let s0 = (a >> 2 | a << 30) ^ (a >> 13 | a << 19) ^ (a >> 22 | a << 10)
			let maj = (a & b) ^ (a & c) ^ (b & c)
			let temp2 = s0 &+ maj

			hVal = g
			g = f
			f = e
			e = d &+ temp1
			d = c
			c = b
			b = a
			a = temp1 &+ temp2
		}

		h[0] = h[0] &+ a
		h[1] = h[1] &+ b
		h[2] = h[2] &+ c
		h[3] = h[3] &+ d
		h[4] = h[4] &+ e
		h[5] = h[5] &+ f
		h[6] = h[6] &+ g
		h[7] = h[7] &+ hVal
	}

	return h.map { String(format: "%08x", $0) }.joined()
}
