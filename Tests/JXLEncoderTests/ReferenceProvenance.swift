import Foundation

/// Locates the checked-out repository from this file's own path. The pin record
/// and the provenance manifest live under `Reference/`, outside any test bundle,
/// so the provenance tests read them from the source tree.
enum RepositoryLayout {
	static var root: URL {
		URL(fileURLWithPath: #filePath)
			.deletingLastPathComponent()  // JXLEncoderTests
			.deletingLastPathComponent()  // Tests
			.deletingLastPathComponent()
	}

	static var pinRecord: URL { root.appendingPathComponent("Reference/libjxl.pin") }
	static var provenanceManifest: URL {
		root.appendingPathComponent("Reference/provenance.tsv")
	}
}

/// `Reference/libjxl.pin`: the single record of which libjxl the reference
/// tools build against. Shell-sourceable `KEY=value` lines so the reference
/// scripts and these tests read the same file; `#` starts a comment.
struct PinRecord {
	let values: [String: String]

	init(contentsOf url: URL) throws {
		fatalError("unimplemented")
	}

	subscript(key: String) -> String? { values[key] }
}

/// Where a committed reference artifact came from. Anything not reproducible
/// from the pinned full libjxl says so here rather than in prose.
enum ProvenanceOrigin: String, CaseIterable {
	/// Produced by the pinned full libjxl recorded in `libjxl.pin`.
	case fullLibjxl = "full-libjxl"
	/// Produced by libjxl-tiny, which is not pinned; frozen until retargeted.
	case inheritedTiny = "inherited-tiny"
	/// Produced by libjpeg-turbo's tools at the version the row records.
	case libjpegTurbo = "libjpeg-turbo"
	/// Captured from a CPU instruction on the host; only regenerable on that
	/// architecture.
	case hostArm64 = "host-arm64"
	/// Supplied by hand, not generated by any tool in this repository.
	case handSupplied = "hand-supplied"
}

enum ProvenanceKind: String {
	/// A file under a test target's `Fixtures/`, checked by content hash.
	case fixture
	/// A generated table compiled into `Sources/`, checked by its header.
	case table
	/// Expected values written inline in a test file rather than a fixture.
	case inline
}

/// One row of `Reference/provenance.tsv`. Columns, tab-separated, in order:
/// path, kind, sha256, origin, generator, invocation, input, upstream, config,
/// consumers.
///
/// `sha256` is present exactly for `fixture` rows and `-` otherwise.
/// `invocation` is the command that produced the artifact and `input` what it
/// read; either is `unrecorded` when the repository doesn't know, so a
/// regenerator can see the gap instead of guessing. `consumers` is a
/// comma-separated list of test files, or `-`.
struct ProvenanceRow: Equatable {
	let path: String
	let kind: ProvenanceKind
	let sha256: String?
	let origin: ProvenanceOrigin
	let generator: String
	let invocation: String
	let input: String
	let upstream: String
	let config: String
	let consumers: [String]
}

struct ProvenanceManifest {
	let rows: [ProvenanceRow]

	/// Throws on a malformed row (wrong column count, unknown kind or origin,
	/// a digest on the wrong kind of row) rather than skipping it, so a typo
	/// can't hide a fixture. Lines starting with `#` are comments.
	init(text: String) throws {
		fatalError("unimplemented")
	}

	init(contentsOf url: URL) throws {
		try self.init(text: String(decoding: try Data(contentsOf: url), as: UTF8.self))
	}
}

