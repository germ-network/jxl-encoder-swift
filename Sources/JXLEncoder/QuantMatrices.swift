	/// Reciprocals used when quantizing.
	///
	/// Two details are load-bearing. The reference divides in double and narrows
	/// (`1.0 / table[i]` with a double literal), and it zeroes the first entry of
	/// each channel: DC is carried by the separate DC image, so multiplying
	/// coefficient 0 by zero keeps it out of the AC stream.
	static let inverseWeights: [Float] = {
		var inv = [Float](repeating: 0, count: weights.count)
		for i in 0..<weights.count {
			inv[i] = Float(1.0 / Double(weights[i]))
		}
		for channel in 0..<3 {
			inv[channel * blockSize] = 0
		}
		return inv
	}()

	static func inverseMatrix(channel: Int) -> ArraySlice<Float> {
		inverseWeights[channel * blockSize..<(channel + 1) * blockSize]
	}

	static func matrix(channel: Int) -> ArraySlice<Float> {
		weights[channel * blockSize..<(channel + 1) * blockSize]
	}
